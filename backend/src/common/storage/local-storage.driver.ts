import { createHmac, timingSafeEqual } from 'node:crypto';
import { promises as fs } from 'node:fs';
import * as path from 'node:path';
import type {
  BucketKind,
  SignDownloadOptions,
  SignUploadOptions,
  StorageDriver,
  StoredObject,
  UploadTarget,
} from './storage.types';

// What a local link allows. Signed with HMAC so it cannot be changed or forged.
export interface LocalToken {
  op: 'put' | 'get';
  b: BucketKind;
  k: string;
  exp: number; // unix seconds
  ct?: string; // put: declared content type, stored next to the file
  max?: number; // put: size limit in bytes
  dn?: string; // get: download file name
}

// Keys are generated by the API (e.g. "courses/12/lessons/40/<uuid>.mp4").
// Anything else, including "..", is refused before touching the disk.
const SAFE_KEY = /^[a-z0-9][a-z0-9/_.-]{0,300}$/i;

export function isSafeKey(key: string): boolean {
  return SAFE_KEY.test(key) && !key.split('/').some((part) => part === '..' || part === '.' || part === '');
}

// Development driver (docs/m2-plan.md phase 3): files live under STORAGE_LOCAL_DIR,
// and the API itself serves time-limited upload and download links
// (LocalStorageController). Not for production: Cloud Run's disk is per instance
// and wiped on restart.
export class LocalStorageDriver implements StorageDriver {
  readonly name = 'local';

  constructor(
    private readonly rootDir: string,
    private readonly publicApiUrl: string,
    private readonly secret: string,
  ) {}

  async signUpload(bucket: BucketKind, key: string, opts: SignUploadOptions): Promise<UploadTarget> {
    const exp = Math.floor(Date.now() / 1000) + opts.ttlSeconds;
    const token = this.sign({ op: 'put', b: bucket, k: key, exp, ct: opts.contentType, max: opts.maxBytes });
    return {
      uploadUrl: `${this.publicApiUrl}/storage/local/${token}`,
      method: 'PUT',
      // octet-stream so Express's JSON/form parsers never consume the body; the
      // real content type travels in the token.
      headers: { 'Content-Type': 'application/octet-stream' },
      expiresAt: new Date(exp * 1000),
    };
  }

  async stat(bucket: BucketKind, key: string): Promise<StoredObject | null> {
    try {
      const [info, meta] = await Promise.all([
        fs.stat(this.filePath(bucket, key)),
        fs.readFile(this.metaPath(bucket, key), 'utf8'),
      ]);
      return { sizeBytes: info.size, contentType: (JSON.parse(meta) as { contentType: string }).contentType };
    } catch {
      return null;
    }
  }

  async readStart(bucket: BucketKind, key: string, bytes: number): Promise<Buffer> {
    const handle = await fs.open(this.filePath(bucket, key), 'r');
    try {
      const buf = Buffer.alloc(bytes);
      const { bytesRead } = await handle.read(buf, 0, bytes, 0);
      return buf.subarray(0, bytesRead);
    } finally {
      await handle.close();
    }
  }

  async signDownload(bucket: BucketKind, key: string, opts: SignDownloadOptions): Promise<string> {
    const exp = Math.floor(Date.now() / 1000) + opts.ttlSeconds;
    return `${this.publicApiUrl}/storage/local/${this.sign({ op: 'get', b: bucket, k: key, exp, dn: opts.downloadName })}`;
  }

  async delete(bucket: BucketKind, key: string): Promise<void> {
    await Promise.all([
      fs.rm(this.filePath(bucket, key), { force: true }),
      fs.rm(this.metaPath(bucket, key), { force: true }),
    ]);
  }

  // ─── Used by LocalStorageController ───────────────────────────────────────

  filePath(bucket: BucketKind, key: string): string {
    if (!isSafeKey(key)) throw new Error(`Unsafe storage key: ${key}`);
    return path.join(this.rootDir, bucket, ...key.split('/'));
  }

  metaPath(bucket: BucketKind, key: string): string {
    return `${this.filePath(bucket, key)}.meta.json`;
  }

  // null when the token is malformed, tampered with or expired.
  verify(token: string): LocalToken | null {
    const [body, sig] = token.split('.');
    if (!body || !sig) return null;
    const expected = Buffer.from(this.hmac(body));
    const given = Buffer.from(sig);
    if (expected.length !== given.length || !timingSafeEqual(expected, given)) return null;
    try {
      const t = JSON.parse(Buffer.from(body, 'base64url').toString('utf8')) as LocalToken;
      if (typeof t.exp !== 'number' || t.exp < Date.now() / 1000 || !isSafeKey(t.k)) return null;
      return t;
    } catch {
      return null;
    }
  }

  private sign(t: LocalToken): string {
    const body = Buffer.from(JSON.stringify(t)).toString('base64url');
    return `${body}.${this.hmac(body)}`;
  }

  private hmac(body: string): string {
    return createHmac('sha256', this.secret).update(body).digest('base64url');
  }
}
